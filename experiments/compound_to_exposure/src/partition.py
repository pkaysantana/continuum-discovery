import hashlib
import numpy as np
import pandas as pd
from rdkit import Chem
from rdkit.Chem.Scaffolds import MurckoScaffold

def get_scaffold_key(smiles):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None
    
    # Multicomponent check
    frags = Chem.GetMolFrags(mol, asMols=True)
    if len(frags) > 1:
        # largest fragment by heavy atom count
        frag_mols = [(frag.GetNumHeavyAtoms(), Chem.MolToSmiles(frag, canonical=True), frag) for frag in frags]
        # sort by heavy atoms (descending), then SMILES (ascending)
        frag_mols.sort(key=lambda x: (-x[0], x[1]))
        mol = frag_mols[0][2]
        
    try:
        scaffold = MurckoScaffold.MurckoScaffoldSmiles(mol=mol, includeChirality=False)
        if scaffold == '':
            return '__ACYCLIC__'
        return scaffold
    except:
        return '__ACYCLIC__'

def compute_master_partition(df_all_1102, interior_731_ids):
    """
    df_all_1102: DataFrame containing all 1102 records with 'chembl_id' and 'canonical_smiles'.
    interior_731_ids: Set of chembl_ids that belong to the primary 731 cohort.
    
    Returns a DataFrame representing splits/master_partition.csv
    Columns: chembl_id, canonical_smiles, scaffold_key, scaffold_group_id, partition, cv_fold, cohort
    """
    df = df_all_1102.copy()
    
    # 1. Compute scaffold key
    df['scaffold_key'] = df['canonical_smiles'].apply(get_scaffold_key)
    
    # 2. Group by scaffold key and sort
    # We need to know how many 731-cohort compounds each group has
    df['is_731'] = df['chembl_id'].isin(interior_731_ids)
    
    group_stats = df.groupby('scaffold_key').agg(
        total_count=('chembl_id', 'count'),
        count_731=('is_731', 'sum')
    ).reset_index()
    
    # Sort order: sha256 int -> lexicographic
    def group_sort_key(key):
        hash_hex = hashlib.sha256(key.encode("utf-8")).hexdigest()[:8]
        return (int(hash_hex, 16), key)
        
    group_stats['sort_tuple'] = group_stats['scaffold_key'].apply(group_sort_key)
    group_stats = group_stats.sort_values(by='sort_tuple').reset_index(drop=True)
    group_stats['scaffold_group_id'] = range(len(group_stats)) # Optional: assign an ID
    
    # 3. Holdout assignment
    target_holdout_size = 0.20 * len(interior_731_ids) # 731 * 0.20 = 146.2
    
    holdout_groups = set()
    cv_groups = set()
    
    current_holdout_731_count = 0
    
    for _, row in group_stats.iterrows():
        key = row['scaffold_key']
        g_count = row['count_731']
        
        # 4. If single group is itself larger than holdout budget
        if g_count > target_holdout_size:
            cv_groups.add(key)
            continue
            
        if current_holdout_731_count < target_holdout_size:
            holdout_groups.add(key)
            current_holdout_731_count += g_count
        else:
            cv_groups.add(key)
            
    # 5. Inner fold assignment for CV pool
    fold_counts_731 = {0: 0, 1: 0, 2: 0, 3: 0, 4: 0}
    group_folds = {}
    
    for _, row in group_stats.iterrows():
        key = row['scaffold_key']
        if key in cv_groups:
            # fold with fewest 731-cohort compounds, ties broken by lowest fold index
            best_fold = min(fold_counts_731.keys(), key=lambda f: (fold_counts_731[f], f))
            group_folds[key] = best_fold
            fold_counts_731[best_fold] += row['count_731']
            
    # Assign back to main df
    df['partition'] = df['scaffold_key'].apply(lambda x: 'holdout' if x in holdout_groups else 'cv')
    df['cv_fold'] = df['scaffold_key'].map(group_folds)
    df['cv_fold'] = df['cv_fold'].astype('Int64') # Nullable int
    
    # cohort column mapping
    # we need to map from the original df attributes to cohort name
    # df_all_1102 should ideally already have a 'cohort' column. If not, we map it based on logic.
    # In practice, we will join this with the cohorts generated by dataset.py
    
    return df
